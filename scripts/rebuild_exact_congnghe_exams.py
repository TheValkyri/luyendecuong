def make_mcq(q_id, number, section, stem, opt_a, opt_b, opt_c, opt_d, correct_letter, level="comprehension", points=0.25):
    options = [
        {"id": f"{q_id}_opt_A", "label": "A", "content": opt_a},
        {"id": f"{q_id}_opt_B", "label": "B", "content": opt_b},
        {"id": f"{q_id}_opt_C", "label": "C", "content": opt_c},
        {"id": f"{q_id}_opt_D", "label": "D", "content": opt_d},
    ]
    correct_id = f"{q_id}_opt_{correct_letter}"
    return {
        "id": q_id,
        "number": number,
        "section": section,
        "type": "single_choice",
        "cognitive_level": level,
        "points": points,
        "stem": stem,
        "stem_blocks": [
            {
                "block_id": f"{q_id}_blk_1",
                "order_index": 0,
                "type": "paragraph",
                "content": stem
            }
        ],
        "formulas": [],
        "explanation": f"Đáp án đúng theo đề cương: {correct_letter}.",
        "validation": {
            "confidence": 1.0,
            "needs_review": False,
            "verified_by_human": True,
            "critical_errors": [],
            "warnings": []
        },
        "options": options,
        "answer_key": {
            "question_type": "single_choice",
            "correct_option_id": correct_id
        }
    }

def make_tf(q_id, number, section, stem, stmts, points=1.0):
    # stmts: list of (key, text, is_true)
    statements = [
        {"id": f"{q_id}_stmt_{k}", "key": k, "content": text}
        for (k, text, _) in stmts
    ]
    statement_answers = {
        f"{q_id}_stmt_{k}": is_true
        for (k, _, is_true) in stmts
    }
    return {
        "id": q_id,
        "number": number,
        "section": section,
        "type": "true_false_cluster",
        "cognitive_level": "comprehension",
        "points": points,
        "stem": stem,
        "stem_blocks": [
            {
                "block_id": f"{q_id}_blk_1",
                "order_index": 0,
                "type": "paragraph",
                "content": stem
            }
        ],
        "formulas": [],
        "explanation": "Đánh giá Đúng/Sai theo chuẩn kiến thức đề cương bài học.",
        "validation": {
            "confidence": 1.0,
            "needs_review": False,
            "verified_by_human": True,
            "critical_errors": [],
            "warnings": []
        },
        "statements": statements,
        "answer_key": {
            "question_type": "true_false_cluster",
            "statement_answers": statement_answers
        }
    }

